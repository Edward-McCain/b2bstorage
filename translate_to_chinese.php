// Функция для перевода текста
function translateToChinese($text, $translations) {
    // Сначала ищем точное совпадение
    if (isset($translations[$text])) {
        return $translations[$text];
    }
    
    // Если нет точного совпадения, пытаемся перевести по частям
    $words = explode(' ', $text);
    $translatedWords = [];
    
    foreach ($words as $word) {
        $cleanWord = trim($word, '.,!?()[]{}');
        if (isset($translations[$cleanWord])) {
            $translatedWords[] = $translations[$cleanWord];
        } else {
            $translatedWords[] = $cleanWord; // Оставляем как есть, если нет перевода
        }
    }
    
    return implode('', $translatedWords); // Китайский не использует пробелы между словами
}

